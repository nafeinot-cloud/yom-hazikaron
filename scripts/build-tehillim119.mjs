import { readFileSync, writeFileSync } from 'fs';

const raw = readFileSync(new URL('./raw-tehillim-119.txt', import.meta.url), 'utf8');
const lines = raw.split('\n').map((l) => l.trim()).filter(Boolean);

if (lines.length !== 176) {
  console.error(`Expected 176 verses, got ${lines.length}`);
  process.exit(1);
}

// Manually inspected every verse containing a pipe (׀) in the source (8
// total). Three are genuine ketiv/qere pairs — an unpointed ketiv word
// glued directly to the pointed qere word (verses 79, 147, 161); those
// bare fragments are removed by name below. The other five (52, 69, 104,
// 128, 156) are just a prosodic pipe (paseq) between two ordinary, fully
// pointed words, handled by the generic "pipe -> space" step.
const KETIV_FRAGMENTS = ['וידעו', 'לדבריך', 'ומדבריך'];

function clean(line) {
  let s = line;
  for (const frag of KETIV_FRAGMENTS) {
    s = s.replace(frag + '׀', '');
  }
  s = s.replace(/׀/g, ' '); // remaining pipes are just prosodic separators
  s = s.replace(/[֑-֯]/g, ''); // cantillation (te'amim) marks; nikkud is untouched
  return s.replace(/\s+/g, ' ').trim();
}

const ALPHABET = ['א','ב','ג','ד','ה','ו','ז','ח','ט','י','כ','ל','מ','נ','ס','ע','פ','צ','ק','ר','ש','ת'];

const stanzas = {};
ALPHABET.forEach((letter, i) => {
  const verses = lines.slice(i * 8, i * 8 + 8).map(clean);
  stanzas[letter] = verses;
});

const out = `// Psalm 119 (Tehillim קי״ט), full Hebrew text, grouped into its 22
// alphabetical stanzas of 8 verses each (one stanza per Hebrew letter).
// Source: Sefaria "Miqra according to the Masorah" text (public domain
// Masoretic text). Cantillation (te'amim) marks stripped for on-screen
// readability; nikkud (vowel points, including meteg) retained.
//
// Generated by scripts/build-tehillim119.mjs — do not hand-edit; re-run the
// script against scripts/raw-tehillim-119.txt if a correction is needed.

export const TEHILLIM_119 = ${JSON.stringify(stanzas, null, 2)};
`;

writeFileSync(new URL('../src/data/tehillim119.js', import.meta.url), out, 'utf8');
console.log('Wrote src/data/tehillim119.js —', ALPHABET.length, 'stanzas,', lines.length, 'verses total.');

// Spot-check every verse that originally had a pipe.
const checks = [
  [52, 'ז', 3], [69, 'ט', 4], [79, 'י', 6], [104, 'מ', 7],
  [128, 'ע', 7], [147, 'ק', 2], [156, 'ר', 3], [161, 'ש', 0],
];
for (const [verseNum, letter, idx] of checks) {
  console.log(`verse ${verseNum} (${letter}[${idx}]):`, stanzas[letter][idx]);
}
