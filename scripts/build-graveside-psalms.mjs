import { writeFileSync } from 'fs';
import { RAW_PSALMS } from './raw-graveside-psalms.mjs';

const EXPECTED_COUNTS = { 33: 22, 16: 11, 17: 15, 72: 20, 91: 16, 104: 35, 130: 8 };

function clean(line) {
  return line
    .replace(/[א-ת]{2,}׀/g, '') // stray bare ketiv fragments (none expected here, kept for safety)
    .replace(/׀/g, ' ')
    .replace(/[֑-֯]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

const out = {};
for (const [chapter, verses] of Object.entries(RAW_PSALMS)) {
  const expected = EXPECTED_COUNTS[chapter];
  if (verses.length !== expected) {
    console.error(`Chapter ${chapter}: expected ${expected} verses, got ${verses.length}`);
    process.exit(1);
  }
  out[chapter] = verses.map(clean);
}

const content = `// Full Hebrew text of the seven Psalms traditionally recited at the
// graveside on a yahrzeit, in addition to Psalm 119. Source: Sefaria
// (Miqra according to the Masorah, public-domain Masoretic text), verse
// content cross-checked against kadisha.org/prayers-by-name (word for
// word match). Cantillation marks stripped for readability; nikkud kept.
//
// Generated by scripts/build-graveside-psalms.mjs from
// scripts/raw-graveside-psalms.mjs.

export const GRAVESIDE_PSALM_TEXT = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(new URL('../src/data/gravesidePsalms.js', import.meta.url), content, 'utf8');
console.log('Wrote src/data/gravesidePsalms.js —', Object.keys(out).length, 'psalms');
for (const [chapter, verses] of Object.entries(out)) {
  console.log(`  ${chapter}: ${verses.length} verses, first: "${verses[0].slice(0, 40)}..."`);
}
